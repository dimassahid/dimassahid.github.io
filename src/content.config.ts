import { defineCollection, z } from "astro:content";
import { glob } from "astro/loaders";

/**
 * Shared frontmatter contract for every article.
 *
 * `lang` + `translationKey` form the translation pair: one file per language
 * sharing the same translationKey. The sync script from Notion writes exactly
 * these fields, so keep the schema and the script in sync.
 */
const articleSchema = z.object({
  title: z.string().min(1, "title is required"),
  description: z.string().min(1, "description is required"),
  lang: z.enum(["id", "en"]).default("id"),
  translationKey: z.string().optional(),
  category: z.string().default("general"),
  tags: z.array(z.string()).default([]),
  publishDate: z.coerce.date(),
  updatedDate: z.coerce.date().optional(),
  draft: z.boolean().default(false),
  featured: z.boolean().default(false),
  /** Demonstration content that ships with the template. Rendered with a banner. */
  sample: z.boolean().default(false),
  author: z.string().optional(),
  cover: z.string().optional(),
  /** Marks whether this file is the source, machine output, or a reviewed translation. */
  translationStatus: z.enum(["original", "machine", "reviewed"]).default("original"),
  /** Language of the source article this file was translated from. */
  sourceLang: z.enum(["id", "en"]).optional(),
  /** Set when the file was generated by sync-notion.mjs. */
  notionId: z.string().optional(),
  notionUrl: z.string().url().optional(),
  notionLastEdited: z.coerce.date().optional()
});

const writeups = defineCollection({
  loader: glob({ pattern: "**/*.{md,mdx}", base: "./src/content/writeups" }),
  schema: articleSchema
});

const notes = defineCollection({
  loader: glob({ pattern: "**/*.{md,mdx}", base: "./src/content/notes" }),
  schema: articleSchema
});

export const collections = { writeups, notes };
